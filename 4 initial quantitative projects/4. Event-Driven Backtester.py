event_dates = pd.to_datetime(event_dates)

event_results = []

for event in event_dates:
    if event not in prices.index:
        continue

    event_price = prices.loc[event]

    row = {"Event Date": event}

    for horizon in [1, 2, 3, 5, 10]:
        future_dates = prices.index[prices.index > event]

        if len(future_dates) >= horizon:
            future_date = future_dates[horizon - 1]
            future_price = prices.loc[future_date]
            row[f"Return_{horizon}d"] = future_price / event_price - 1

    event_results.append(row)

event_df = pd.DataFrame(event_results)

