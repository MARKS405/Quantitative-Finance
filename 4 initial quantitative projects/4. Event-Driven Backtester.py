"""# 2. Regímenes"""

def classify_period(date):
    year = date.year

    if year == 2020:
        return "Crisis"
    elif year == 2022:
        return "Tightening"
    elif year in [2019, 2021, 2023, 2024, 2025]:
        return "Normal / Easing"
    else:
        return "Other"

