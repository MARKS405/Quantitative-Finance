"""# 6. Métricas comparables"""

def performance_metrics(returns, periods_per_year=252):
    returns = returns.dropna()

    cumulative_return = (1 + returns).prod() - 1
    years = len(returns) / periods_per_year
    cagr = (1 + cumulative_return) ** (1 / years) - 1

    volatility = returns.std() * np.sqrt(periods_per_year)
    sharpe = cagr / volatility

    cumulative = (1 + returns).cumprod()
    peak = cumulative.cummax()
    drawdown = cumulative / peak - 1
    max_drawdown = drawdown.min()

    return pd.Series({
        "Cumulative Return": cumulative_return,
        "CAGR": cagr,
        "Volatility": volatility,
        "Sharpe": sharpe,
        "Max Drawdown": max_drawdown
    })

metrics = pd.DataFrame({
    "HMM Strategy OOS": performance_metrics(test["Strategy_Return"]),
    "Buy & Hold": performance_metrics(test["BuyHold_Return"])
})

