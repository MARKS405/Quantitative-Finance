kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
data["Regime"] = kmeans.fit_predict(X_scaled)

regime_names = {
    0: "Stress / Crisis",
    1: "Normal / Bullish",
    2: "Correction / Weak Market"
}

data["Regime_Name"] = data["Regime"].map(regime_names)

data[["Close", "Return", "Vol_21d", "Drawdown", "Regime", "Regime_Name"]].head()

regime_summary = data.groupby("Regime")[["Return", "Vol_21d", "Drawdown"]].mean()
